import { describe, expect, it } from 'vitest';
import { isPublicIp } from '@/lib/security/ip';

describe('isPublicIp (SSRF guard)', () => {
  it.each([
    '127.0.0.1', '10.1.2.3', '172.16.0.1', '192.168.1.1',
    '169.254.169.254', '100.64.0.1', '0.0.0.0',
    '192.0.0.8', '192.0.2.10', '192.88.99.1',
    '198.18.0.1', '198.51.100.7', '203.0.113.9', '240.0.0.1',
    '::', '::1', 'fd00::1', 'fe80::1', 'ff02::1',
    '::ffff:127.0.0.1', '::ffff:7f00:1', '0:0:0:0:0:ffff:7f00:1',
    '::ffff:10.0.0.1', '::192.168.1.1',
    '2001:db8::1', '2001:0::1', '2002:7f00:1::1', '3fff::1',
    'not-an-ip',
  ])('rejects %s', (ip) => expect(isPublicIp(ip)).toBe(false));

  it.each([
    '8.8.8.8', '1.1.1.1', '93.184.216.34', '203.0.114.1',
    '2606:4700:4700::1111', '2001:4860:4860::8888',
  ])('accepts %s', (ip) => expect(isPublicIp(ip)).toBe(true));
});
